
# backend/approvals.py

def check_approvals(
    document_type: str,
    changes_system_access: bool = False,
    it_project: bool = False,
) -> dict:
    """Определяет обязательные согласования по матрице"""

    rules = {
        "weekend_work": {
            "name": "Приказ о работе в выходной день",
            "departments": [
                "Юридический департамент",
                "Департамент ДОУ",
                "Кадровое подразделение",
            ],
            "reason": "Для этой категории матрица предусматривает обязательное согласование с указанными подразделениями.",
        },
        "transfer_cases": {
            "name": "Приказ о приёме и передаче дел и имущества",
            "departments": [
                "Юридический департамент",
                "Департамент ДОУ",
                "Кадровое подразделение",
            ],
            "reason": "Матрица предусматривает обязательное согласование при изменении ответственных за дела и имущество.",
        },
        "it_system": {
            "name": "Документ по информационной системе",
            "departments": [
                "Юридический департамент",
                "Департамент ДОУ",
                "Подразделение информационной безопасности",
                "ИТ-подразделение",
            ],
            "reason": "Матрица предусматривает согласование документов о вводе, выводе или пилотной эксплуатации информационных систем.",
        },
        "payment": {
            "name": "Приказ о выплатах или надбавках",
            "departments": [
                "Департамент ДОУ",
                "Кадровое подразделение",
            ],
            "reason": "Матрица предусматривает согласование с ДОУ и кадровым подразделением.",
        },
        "working_group": {
            "name": "Распоряжение о создании рабочей группы",
            "departments": [
                "Департамент ДОУ",
                "Кадровое подразделение",
            ],
            "reason": "Матрица предусматривает обязательное согласование с ДОУ и кадровым подразделением.",
        },
        "project_committee": {
            "name": "Распоряжение о создании проектного комитета",
            "departments": [
                "Департамент ДОУ",
                "Кадровое подразделение",
            ],
            "reason": "Матрица предусматривает обязательное согласование с ДОУ и кадровым подразделением.",
        },
        "other_order": {
            "name": "Иной приказ",
            "departments": [
                "Юридический департамент",
                "Департамент ДОУ",
            ],
            "reason": "Для указанной категории матрица предусматривает согласование с юридическим департаментом и ДОУ.",
        },
    }

    if document_type not in rules:
        return {
            "status": "needs_clarification",
            "message": (
                "Не удалось однозначно определить категорию документа. "
                "Уточните его вид и назначение."
            ),
            "departments": [],
            "conditions": [],
        }

    rule = rules[document_type]
    departments = list(rule["departments"])
    conditions = []

    if document_type == "transfer_cases" and changes_system_access:
        departments.append(
            "Подразделение информационной безопасности"
        )
        conditions.append(
            "Изменение системных доступов требует согласования с информационной безопасностью."
        )

    if document_type in {"working_group", "project_committee"} and it_project:
        departments.append("ИТ-подразделение")
        conditions.append(
            "ИТ-подразделение подключается, если группа или комитет связаны с ИТ-проектом или информационной системой."
        )

    return {
        "status": "success",
        "document_type": document_type,
        "document_name": rule["name"],
        "departments": departments,
        "reason": rule["reason"],
        "conditions": conditions,
        "warning": (
            "Матрица не исчерпывающая: дополнительно включите подразделения, "
            "полномочия или компетенция которых затрагиваются документом. "
            "Перед использованием проверьте актуальную редакцию матрицы."
        ),
    }
